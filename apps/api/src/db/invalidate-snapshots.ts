import type { BetterSQLite3Database } from 'drizzle-orm/better-sqlite3';
import { portfolioSnapshots, snapshotPositions } from './schema';

/**
 * Стирает накопленную историю снимков (portfolio_snapshots + snapshot_positions).
 *
 * Снимок — кумулятивный NAV «на сейчас» (весь журнал операций без фильтра по дате),
 * зафиксированный под датой захвата (SnapshotsService.capture()). Правка/удаление
 * УЖЕ СУЩЕСТВУЮЩЕЙ операции задним числом меняет то, что должно было быть посчитано
 * на каждую прошлую дату захвата — но без исторических цен на каждый день прошлые
 * снимки нельзя пересчитать под исправленные данные (реальный кейс: дашборд показал
 * −83.68% «просадки», сравнив снимок до полной замены журнала операций со снимком
 * после — цифры относились к разным, несравнимым наборам данных).
 *
 * Вместо показа несравнимых эпох («было» vs «стало») стираем всю историю снимков —
 * она начнёт копиться заново со следующего «Обновить цены», уже на верных данных.
 * Добавление НОВОЙ операции сюда не относится — это не меняет задним числом то, что
 * уже было верно зафиксировано, а просто продолжает журнал вперёд.
 */
export function invalidateSnapshots(db: BetterSQLite3Database): void {
  db.delete(snapshotPositions).run();
  db.delete(portfolioSnapshots).run();
}
